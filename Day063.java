import java.util.Scanner;

public class mpangkatn {
    public static void main(String[] args) {
        Scanner s = new Scanner(System.in);
        int m = s.nextInt();
        int N = s.nextInt();

        for (int i = N; i <= N; i++) {
                m *= m;  
        }

        System.out.print(m);
    }
}
